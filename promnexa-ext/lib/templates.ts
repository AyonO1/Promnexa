export const PROMPT_TEMPLATES: PromptTemplate[] = [
  ...CORE_TEMPLATES,
  ...(curatedImported as unknown as PromptTemplate[]),
];

// ---- Template Search ----
export function searchTemplates(
  query: string,
  category?: Category
): PromptTemplate[] {
  let results = PROMPT_TEMPLATES;

  if (category && category !== 'general') {
    results = results.filter(t => t.category === category);
  }

  if (query.trim()) {
    const lowerQuery = query.toLowerCase();
    results = results.filter(t =>
      t.title.toLowerCase().includes(lowerQuery) ||
      t.description.toLowerCase().includes(lowerQuery) ||
      t.tags.some(tag => tag.toLowerCase().includes(lowerQuery)) ||
      (t.subcategory && t.subcategory.toLowerCase().includes(lowerQuery))
    );
  }

  return results;
}

// ---- Get Templates by Category ----
export function getTemplatesByCategory(category: Category): PromptTemplate[] {
  if (category === 'general') return PROMPT_TEMPLATES;
  return PROMPT_TEMPLATES.filter(t => t.category === category);
}

// ---- Get Unique Subcategories ----
export function getSubcategories(category?: Category): string[] {
  const templates = category ? getTemplatesByCategory(category) : PROMPT_TEMPLATES;
  const subcategories = new Set<string>();
  templates.forEach(t => {
    if (t.subcategory) subcategories.add(t.subcategory);
  });
  return Array.from(subcategories).sort();
}
